#!/usr/bin/env node
// Regenerates src/devtools-devices.mjs from Chrome DevTools' own device list
// (devtools-frontend, front_end/models/emulation/EmulatedDevices.ts), so the "DevTools"
// tab of the device menu is the list Chrome ships. Run it when Chrome adds devices:
//   node tools/sync-devtools-devices.mjs [path-or-url]
import { readFileSync, writeFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';

const SOURCE = 'https://raw.githubusercontent.com/ChromeDevTools/devtools-frontend/main/front_end/models/emulation/EmulatedDevices.ts';
const from = process.argv[2] || SOURCE;
const src = /^https?:/.test(from) ? await (await fetch(from)).text() : readFileSync(from, 'utf8');

// The list is object literals between two markers; a few titles are i18n strings.
const strings = Object.fromEntries([...src.matchAll(/^\s*(\w+):\s*'([^']+)',/gm)].map((m) => [m[1], m[2]]));
const body = src.split('// DEVICE-LIST-BEGIN')[1]?.split('// DEVICE-LIST-END')[0];
if (!body) throw new Error('device list markers not found — has the file moved?');
const list = runInNewContext(`[${body}]`, {
  i18nLazyString: (s) => s,
  UIStrings: new Proxy({}, { get: (_, k) => strings[k] ?? k }),
});

/* One menu section per kind of screen, in the order you reach for them. */
const groupOf = (d) => {
  const t = d.title;
  if (/Fold|Duo/.test(t)) return 'Foldable';
  if (d.type === 'notebook' || d.type === 'smart-display') return 'Laptop & display';
  if (d.type === 'tablet' || /Tab /.test(t)) return 'Tablet';
  if (/iPhone/.test(t)) return 'iPhone';
  return 'Android';
};
const GROUPS = ['iPhone', 'Android', 'Foldable', 'Tablet', 'Laptop & display'];
const slug = (t) => t.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const devices = list
  .map((d) => {
    const s = d.screen;
    // the orientation the device opens in: portrait for handhelds, the only mode for laptops
    const first = d.modes?.[0]?.orientation ?? (d.type === 'notebook' ? 'horizontal' : 'vertical');
    const open = first.startsWith('horizontal') ? s.horizontal : s.vertical;
    const portraitMode = d.modes?.find((m) => m.orientation === 'vertical');
    const row = {
      id: slug(d.title), label: d.title, group: groupOf(d),
      w: open.width, h: open.height, dpr: s['device-pixel-ratio'],
      // can it turn: a second plain orientation, not a fold state
      rotates: !d.modes || d.modes.some((m) => m.orientation === (first === 'vertical' ? 'horizontal' : 'vertical')),
      mobile: (d.capabilities || []).includes('mobile'),
    };
    // what the real screen takes from the page at the top and bottom, and the camera cut-out
    if (portraitMode?.['safe-area-insets']) row.insets = portraitMode['safe-area-insets'];
    if (portraitMode?.cutout) row.cutout = portraitMode.cutout;
    return { order: d.order ?? 999, row };
  })
  .sort((a, b) => GROUPS.indexOf(a.row.group) - GROUPS.indexOf(b.row.group) || a.order - b.order)
  .map(({ row }) => row);

